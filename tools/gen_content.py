#!/usr/bin/env python3
"""Generate lib/content/*.g.dart from the sourced JSON in content/.

The JSON files are the record of where every sentence came from (FAA
document, edition, URL, sha256 of the file read). The app compiles the
generated Dart so the content works offline and in widget tests.

    python3 tools/gen_content.py          # writes lib/content/*.g.dart
    python3 tools/gen_content.py --check  # exits 1 if they are stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "content"
OUT = ROOT / "lib" / "content"
HEADER = "// GENERATED by tools/gen_content.py from content/{src}. Do not edit.\n"


def s(v):
    """A Dart single-quoted string literal."""
    v = (v or "").replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return "'" + v.replace("\r", "\\r").replace("\n", "\\n") + "'"


def item(i):
    return f"SourcedLine({s(i['text'])}, {s(i['cite'])})"


def gen_instruments():
    d = json.loads((SRC / "instruments_airport_ops.json").read_text())
    out = [HEADER.format(src="instruments_airport_ops.json"),
           "import 'sourced.dart';\n"]
    out.append("const instrumentSources = <SourceDoc>[")
    for src in d["sources"]:
        out.append(f"  SourceDoc({s(src['title'])}, {s(src.get('docNumber', ''))}, "
                   f"{s(src.get('edition', ''))}, {s(src['url'])}),")
    out.append("];\n")
    out.append("const instrumentLessons = <InstrumentLesson>[")
    for i in d["instruments"]:
        out.append(f"  InstrumentLesson(id: {s(i['id'])}, name: {s(i['name'])},")
        for k in ("shows", "works", "read", "errors"):
            out.append(f"    {k}: [")
            out.extend(f"      {item(x)}," for x in i[k])
            out.append("    ],")
        out.append("  ),")
    out.append("];\n")
    a = d["airportOps"]
    out.append("const trafficPattern = <SourcedLine>[")
    out.extend(f"  {item(x)}," for x in a["pattern"])
    out.append("];\n")
    out.append("const airportSigns = <AirportSign>[")
    for x in a["signs"]:
        out.append(f"  AirportSign({s(x['type'])}, {s(x['colors'])}, {item(x['meaning'])}),")
    out.append("];\n")
    out.append("const airportMarkings = <SourcedLine>[")
    out.extend(f"  {item(x)}," for x in a["markings"])
    out.append("];")
    return "instruments.g.dart", "\n".join(out) + "\n"


def short_edition(e):
    e = (e or "").strip()
    for sep in (" (", ";"):
        if sep in e:
            e = e.split(sep)[0]
    return e.strip().rstrip(".")


def gen_library():
    books = json.loads((SRC / "faa_library.json").read_text())
    out = [HEADER.format(src="faa_library.json"), "import 'sourced.dart';\n",
           "const faaLibrary = <LibraryBook>["]
    for b in books:
        out.append(f"  LibraryBook(id: {s(b['id'])}, title: {s(b['title'])}, "
                   f"docNumber: {s(b.get('docNumber', ''))}, "
                   f"edition: {s(b.get('editionShort') or short_edition(b.get('edition')))}, "
                   f"url: {s(b['url'])}, pdf: {'true' if b.get('format') == 'pdf' else 'false'}, "
                   f"pages: {int(b['pages']) if b.get('pages') else 'null'}, chapters: [")
        for c in b.get("chapters") or []:
            out.append(f"    LibraryChapter({s(str(c['n']))}, {s(c['title'])}, {s(c.get('url'))}),")
        out.append("  ]),")
    out.append("];")
    return "faa_library.g.dart", "\n".join(out) + "\n"


def gen_questions():
    """FAA PAR sample questions whose answer is proved by quoted FAA text
    (par_answers.json) AND was confirmed by an independent re-check
    (par_verification.json). Anything else stays out of the app."""
    qs = json.loads((SRC / "par_sample_questions.json").read_text())
    ans = {a["id"]: a for a in json.loads((SRC / "par_answers.json").read_text())["answers"]}
    ver = json.loads((SRC / "par_verification.json").read_text())
    # Confirmed means the reviewer reached the same letter on its own, found
    # the quote verbatim and the cite right.
    ok = {v["id"] for v in ver["verdicts"]
          if v["verdict"] == "confirmed" and v["quoteFoundVerbatim"]
          and v["citeCorrect"] and v["explanationAccurate"]
          and v["id"] in ans and v["myAnswer"] == ans[v["id"]]["answer"]}
    src = qs["source"]
    out = [HEADER.format(src="par_sample_questions.json + par_answers.json + par_verification.json"),
           "import 'knowledge_question.dart';\n",
           "/// Shown under the Practice list.",
           "const faaQuestionsSourceNote = " + s(
               "Questions: the FAA's Private Pilot-Airplane (PAR) Sample Questions "
               "(dated 8/10/2021), word for word. "
               "The FAA publishes no answer key: each answer here is shown in the quoted FAA "
               "text (14 CFR, AIM or an FAA handbook) and was checked a second time. "
               "Questions that need a figure from the testing supplement are not included yet.") + ";\n",
           "const faaSampleQuestions = <KnowledgeQuestion>["]
    letters = "ABC"
    for q in qs["questions"]:
        a = ans.get(q["id"])
        if not a or a["status"] != "proven" or q["id"] not in ok:
            continue
        if q.get("figure") or q.get("inlineImage"):
            continue
        ch = q["choices"]
        out.append("  KnowledgeQuestion(")
        out.append(f"    id: {s(q['id'])},")
        out.append(f"    stem: {s(q['stem'])},")
        out.append(f"    choices: [{s(ch['A'])}, {s(ch['B'])}, {s(ch['C'])}],")
        out.append(f"    answer: {letters.index(a['answer'])},")
        out.append(f"    explanation: {s(a['explanation'])},")
        out.append(f"    quote: {s(a['quote'])},")
        out.append(f"    cite: {s(a['cite'])},")
        out.append(f"    acsCode: {s(q['faaRef']['acsCode'])},")
        out.append(f"    topic: {s(q['topic'])},")
        out.append("  ),")
    out.append("];")
    return "faa_questions.g.dart", "\n".join(out) + "\n"


GENERATORS = [gen_instruments, gen_library, gen_questions]


def main():
    check = "--check" in sys.argv
    stale = []
    for g in GENERATORS:
        name, text = g()
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote lib/content/{name}")
    if stale:
        print("stale: " + ", ".join(stale) + " (run tools/gen_content.py)")
        sys.exit(1)


if __name__ == "__main__":
    main()
